import { api } from '../api';
import type { ReportDocument } from '../api/types';
import { RefreshCw } from '../components/icons';
import { Badge } from '../components/ui/Badge';
import { Banner } from '../components/ui/Banner';
import { Button } from '../components/ui/Button';
import { Card, CardBody, CardHeader } from '../components/ui/Card';
import { JsonView } from '../components/ui/JsonView';
import { PageHeader } from '../components/ui/PageHeader';
import { Async, EmptyState } from '../components/ui/State';
import { useResource } from '../hooks/useResource';
import { formatRatio, summariseSensorEval, type SensorEvalView } from '../lib/evalReport';
import { formatNumber, humanize } from '../lib/format';
import { Link, useSearchParams } from '../lib/router';

const dash = (n: number | null) => (n === null ? '—' : formatNumber(n));

function SensorEval({ v }: { v: SensorEvalView }) {
  return (
    <div className="stack">
      <Banner tone="warning" title="Synthetic data and a scripted model">
        {v.synthetic ? 'The traffic was generated by scripts in this repository and the labels come from how it was built; it is not real network behaviour. ' : ''}
        {v.fakeModel ? 'The model is a scripted stand-in, so these numbers describe the deterministic layers and the plumbing, not Gemini and not production accuracy.' : ''}
        {v.limits.length ? <ul className="bullets">{v.limits.map((l, i) => <li key={i}>{l}</li>)}</ul> : null}
      </Banner>
      {v.violations > 0 ? <Banner tone="critical" title={`${v.violations} safety invariant violation(s) were recorded`}>Open the raw report below.</Banner> : <p className="muted">No safety invariant was violated in this run (for example: no attack closed by the model alone, no action executed).</p>}
      {v.profiles.map((p) => (
        <Card key={p.name}>
          <CardHeader title={`Model behaviour: ${humanize(p.name)}`} {...(p.assumption ? { description: p.assumption } : {})} />
          <div className="table-wrap">
            <table className="table" data-stack="true" data-density="compact">
              <caption className="visually-hidden">Decision quality per configuration</caption>
              <thead><tr><th scope="col">Configuration</th><th scope="col" className="num">TP</th><th scope="col" className="num">FP</th><th scope="col" className="num">TN</th><th scope="col" className="num">FN</th>
                <th scope="col" className="num">Precision</th><th scope="col" className="num">Recall</th><th scope="col" className="num">F1</th><th scope="col" className="num">Specificity</th><th scope="col" className="num">FPR</th><th scope="col" className="num">FNR</th><th scope="col" className="num">Attacks wrongly closed</th></tr></thead>
              <tbody>
                {p.rows.map((r) => (
                  <tr key={r.config}>
                    <td data-label="Configuration">{humanize(r.config)}</td>
                    <td data-label="TP" className="num">{dash(r.tp)}</td><td data-label="FP" className="num">{dash(r.fp)}</td><td data-label="TN" className="num">{dash(r.tn)}</td><td data-label="FN" className="num">{dash(r.fn)}</td>
                    <td data-label="Precision" className="num">{formatRatio(r.precision)}</td><td data-label="Recall" className="num">{formatRatio(r.recall)}</td><td data-label="F1" className="num">{formatRatio(r.f1)}</td>
                    <td data-label="Specificity" className="num">{formatRatio(r.specificity)}</td><td data-label="FPR" className="num">{formatRatio(r.fpr)}</td><td data-label="FNR" className="num">{formatRatio(r.fnr)}</td>
                    <td data-label="Attacks wrongly closed" className="num">{dash(r.incorrectClosures)}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
          {p.ops.length ? <CardBody><div className="chip-row">{p.ops.map((o) => <Badge key={o.label}>{humanize(o.label)}: {o.value}</Badge>)}</div></CardBody> : null}
        </Card>
      ))}
      {v.providerFailure ? (
        <Card>
          <CardHeader title="Provider failure" description="A model outage injected into some alerts." />
          <CardBody>
            <p>{dash(v.providerFailure.injected)} alerts had an injected outage{v.providerFailure.fraction !== null ? ` (${Math.round(v.providerFailure.fraction * 100)}% of the run)` : ''}.
              {' '}{v.providerFailure.allToReview === true ? 'Every one of them was routed to a person.' : v.providerFailure.allToReview === false ? 'Some were NOT routed to a person: see the raw report.' : ''}
              {' '}{v.providerFailure.attacksClosed === 0 ? 'No attack was closed because of the outage.' : v.providerFailure.attacksClosed ? `${v.providerFailure.attacksClosed} attack(s) were closed.` : ''}</p>
          </CardBody>
        </Card>
      ) : null}
    </div>
  );
}

function Document({ doc }: { doc: ReportDocument }) {
  if (doc.format === 'markdown') return <pre className="report-md" tabIndex={0} aria-label={`Report ${doc.name}`}>{String(doc.content)}</pre>;
  const sensor = summariseSensorEval(doc.content);
  return (
    <div className="stack">
      {sensor ? <SensorEval v={sensor} /> : <Banner tone="info">This report has a shape the console does not summarise. The raw document is below.</Banner>}
      <JsonView value={doc.content} label="Raw report (JSON)" />
    </div>
  );
}

export function EvaluationPage() {
  const [params, setParams] = useSearchParams();
  const list = useResource((s) => api.evaluationReports({ signal: s }), []);
  const selected = params.get('report') ?? '';
  const doc = useResource((s) => api.evaluationReport(selected, { signal: s }), [selected], selected !== '');
  return (
    <>
      <PageHeader title="Evaluation" description="Reports written by the evaluation commands, read from the server's report folder. The console only displays them; it never runs an evaluation or calls a model."
        actions={<Button icon={RefreshCw} onClick={() => { list.reload(); doc.reload(); }} loading={list.refreshing}>Refresh</Button>} />
      <Async resource={list}>
        {(l) => !l.available ? (
          <Card><EmptyState title="No report folder is available">{l.reason ?? 'The server has no evaluation report folder.'} Set WEEK5_EVAL_REPORT_DIR to a folder holding the output of <code>python -m week5.evalrun.sensor_suite</code> or the formal <code>python -m week5.evalrun</code> reports, then restart the API.</EmptyState></Card>
        ) : l.items.length === 0 ? (
          <Card><EmptyState title="The report folder is empty">Run an evaluation command and copy its output files there.</EmptyState></Card>
        ) : (
          <div className="grid grid-2">
            <Card>
              <CardHeader title="Reports" />
              <CardBody>
                <ul role="list" className="stack-sm">
                  {l.items.map((r) => (
                    <li key={r.name} className="row-between">
                      <Link to={`/evaluation?report=${encodeURIComponent(r.name)}`} aria-current={r.name === selected ? 'true' : undefined} onClick={() => setParams({ report: r.name }, { replace: false })}>{r.name}</Link>
                      <span className="muted">{formatNumber(r.bytes)} bytes · {new Date(r.modified * 1000).toLocaleDateString('en-GB')}</span>
                    </li>
                  ))}
                </ul>
              </CardBody>
            </Card>
            <Card>
              <CardHeader title="What these numbers can and cannot say" />
              <CardBody>
                <ul className="bullets">
                  <li>Synthetic reports use generated traffic and a scripted model. They check the pipeline's safety rules, not detection accuracy.</li>
                  <li>Accuracy on real traffic is not measured here. It needs labelled real events and a live model run, and the frozen holdout set is never opened by these tools.</li>
                  <li>Cost appears only when token counts and a verified price configuration exist. Otherwise it says unavailable.</li>
                </ul>
              </CardBody>
            </Card>
          </div>
        )}
      </Async>
      {selected ? (
        <Async resource={doc}>
          {(d) => (<><h2 className="visually-hidden">{d.name}</h2><Document doc={d} /></>)}
        </Async>
      ) : null}
    </>
  );
}
